"""Local Streamlit chat interface for the pretrained ScratchGPT model."""

from pathlib import Path
import sys

import streamlit as st
import torch

# Make the src-layout package importable when running Streamlit from the
# repository root.
PROJECT_ROOT = Path(__file__).resolve().parents[1]
SRC_DIR = PROJECT_ROOT / "src"

if str(SRC_DIR) not in sys.path:
    sys.path.insert(0, str(SRC_DIR))

from scratchgpt.config import GPTConfig
from scratchgpt.generation import generate_tokens
from scratchgpt.model import GPTModel
from scratchgpt.tokenizer import ByteBPETokenizer

CHECKPOINT_PATH = PROJECT_ROOT / "checkpoints" / "scratchgpt_cleaned_10epoch.pt"
TOKENIZER_PATH = PROJECT_ROOT / "checkpoints" / "tokenizer_cleaned.json"


@st.cache_resource(show_spinner="Loading your pretrained ScratchGPT model...")
def load_model_and_tokenizer():
    """Load the saved model weights and matching tokenizer without training."""
    if not CHECKPOINT_PATH.is_file():
        raise FileNotFoundError(f"Model checkpoint not found: {CHECKPOINT_PATH}")

    if not TOKENIZER_PATH.is_file():
        raise FileNotFoundError(f"Tokenizer not found: {TOKENIZER_PATH}")

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # This checkpoint was created by our own training code and contains
    # tensors and ordinary Python data structures.
    checkpoint = torch.load(
        CHECKPOINT_PATH,
        map_location=device,
        weights_only=True,
    )

    saved_config = checkpoint.get("config")
    state_dict = checkpoint.get("model_state_dict")

    if not isinstance(saved_config, dict) or not isinstance(state_dict, dict):
        raise ValueError(
            "The checkpoint does not contain the expected config and "
            "model_state_dict fields."
        )

    config = GPTConfig(**saved_config)
    tokenizer = ByteBPETokenizer.load(TOKENIZER_PATH)

    if tokenizer.vocab_size != config.vocab_size:
        raise ValueError(
            f"Tokenizer vocabulary ({tokenizer.vocab_size}) does not match "
            f"model vocabulary ({config.vocab_size})."
        )

    model = GPTModel(config).to(device)
    model.load_state_dict(state_dict)
    model.eval()

    return model, tokenizer, device


def decode_generated_tokens(token_ids, tokenizer):
    """Decode generated bytes safely, even if a sample ends mid-character."""
    generated_bytes = b"".join(
        tokenizer.token_bytes[token_id] for token_id in token_ids
    )
    return generated_bytes.decode("utf-8", errors="replace")


def generate_reply(
    prompt,
    model,
    tokenizer,
    device,
    max_new_tokens,
    temperature,
    top_k,
    do_sample,
):
    """Generate a continuation using the pretrained model."""
    token_ids = tokenizer.encode(prompt)

    if not token_ids:
        return "Please enter some text."

    # Keep the prompt within the model's trained context window.
    token_ids = token_ids[-model.config.context_length :]

    input_tensor = torch.tensor(
        [token_ids],
        dtype=torch.long,
        device=device,
    )

    with torch.inference_mode():
        output = generate_tokens(
            model=model,
            input_ids=input_tensor,
            max_new_tokens=max_new_tokens,
            temperature=temperature,
            top_k=top_k if do_sample else None,
            do_sample=do_sample,
        )

    new_token_ids = output[0, len(token_ids) :].tolist()
    reply = decode_generated_tokens(new_token_ids, tokenizer)

    return reply.strip() or "(The model generated no visible text.)"


st.set_page_config(
    page_title="ScratchGPT",
    page_icon="💬",
    layout="centered",
)

st.title("💬 ScratchGPT")
st.caption("A small GPT language model pretrained from scratch on TinyStories.")

with st.sidebar:
    st.header("Generation settings")

    max_new_tokens = st.slider(
        "Maximum new tokens",
        min_value=10,
        max_value=128,
        value=48,
        step=8,
        help="More tokens can take longer to generate.",
    )

    do_sample = st.checkbox("Sample responses", value=True)

    temperature = st.slider(
        "Temperature",
        min_value=0.2,
        max_value=1.5,
        value=0.8,
        step=0.1,
        disabled=not do_sample,
        help="Lower values make sampling less random.",
    )

    top_k = st.slider(
        "Top-k",
        min_value=1,
        max_value=100,
        value=40,
        disabled=not do_sample,
        help="Sample from the highest-scoring token candidates.",
    )

    st.divider()

    if st.button("New conversation", use_container_width=True):
        st.session_state.messages = []
        st.rerun()

    st.caption(
        "ScratchGPT is a small next-token language model, not an "
        "instruction-tuned assistant. Responses may be repetitive or "
        "inaccurate."
    )

try:
    model, tokenizer, device = load_model_and_tokenizer()
except Exception as exc:
    st.error(f"Could not load ScratchGPT: {exc}")
    st.info(
        "Check that the cleaned checkpoint and matching tokenizer exist "
        "inside the project's checkpoints folder."
    )
    st.stop()

if "messages" not in st.session_state:
    st.session_state.messages = []

st.caption(
    f"Device: {device.type.upper()} · "
    f"Parameters: {model.parameter_count:,} · "
    f"Context: {model.config.context_length} tokens"
)

for message in st.session_state.messages:
    with st.chat_message(message["role"]):
        st.markdown(message["content"])

user_prompt = st.chat_input("Enter a prompt for ScratchGPT...")

if user_prompt:
    st.session_state.messages.append({"role": "user", "content": user_prompt})

    with st.chat_message("user"):
        st.markdown(user_prompt)

    with st.chat_message("assistant"):
        with st.spinner("Generating text..."):
            try:
                # This is a base language model, so provide the conversation
                # as text context rather than assuming chat-trained behavior.
                recent_messages = st.session_state.messages[-6:]
                context = "\n".join(
                    (
                        "User: " + item["content"]
                        if item["role"] == "user"
                        else "Assistant: " + item["content"]
                    )
                    for item in recent_messages
                )
                context += "\nAssistant:"

                reply = generate_reply(
                    prompt=context,
                    model=model,
                    tokenizer=tokenizer,
                    device=device,
                    max_new_tokens=max_new_tokens,
                    temperature=temperature,
                    top_k=top_k,
                    do_sample=do_sample,
                )

                st.markdown(reply)
                st.session_state.messages.append(
                    {"role": "assistant", "content": reply}
                )

            except Exception as exc:
                st.error(f"Text generation failed: {exc}")
